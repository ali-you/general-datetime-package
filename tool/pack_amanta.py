"""Pack the day-by-day output of generate_amanta.lisp into a Dart table."""

import argparse
import csv
from itertools import groupby
from pathlib import Path

FIRST_YEAR = 2057
LAST_YEAR = 2107

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("csv_path", type=Path)
parser.add_argument("dart_path", type=Path)
args = parser.parse_args()

with args.csv_path.open(newline="") as source:
    rows = [tuple(map(int, row)) for row in csv.reader(source)]

if rows[0][1] >= FIRST_YEAR or rows[-1][1] != LAST_YEAR + 1:
    raise ValueError("Expected the reference to include both surrounding years")

years = set()
previous_day = rows[0][0] - 1
previous_tithi = None
for day, year, month, leap, tithi, repeated in rows:
    if day != previous_day + 1 or not 1 <= month <= 12 or leap not in (0, 1):
        raise ValueError(f"Invalid reference day or month at {day}")
    if not 1 <= tithi <= 30:
        raise ValueError(f"Invalid tithi at {day}")
    if previous_tithi is not None and repeated != (previous_tithi == tithi):
        raise ValueError(f"Invalid repeated tithi at {day}")
    previous_day, previous_tithi = day, tithi
    years.add(year)

if not set(range(FIRST_YEAR - 1, LAST_YEAR + 2)).issubset(years):
    raise ValueError("Reference is missing a year")

supported = [row for row in rows if FIRST_YEAR <= row[1] <= LAST_YEAR]
lines = [
    "// Generated by tool/generate_amanta.lisp and tool/pack_amanta.py.",
    "// Source: Calendrica 4.0 (Reingold and Dershowitz), Apache-2.0.",
    "// Revision: 9afc1f3277b839db1a70c2350d6c708ac83df78f.",
    "",
    f"const int amantaStartDay = {supported[0][0]};",
    "",
    "// Rows: Vikrama year, traditional month, intercalary flag, daily tithis.",
    "// Each tithi is stored as the character with code unit 96 + tithi.",
    "const List<(int, int, bool, String)> amantaMonths = [",
]
seen = set()
for (year, month, leap), days in groupby(supported, key=lambda row: row[1:4]):
    key = (year, month, leap)
    tithis = [row[4] for row in days]
    if key in seen or not 28 <= len(tithis) <= 31:
        raise ValueError(f"Unexpected month {key} of length {len(tithis)}")
    if tithis != sorted(tithis) or tithis[0] not in (1, 2) or tithis[-1] < 29:
        raise ValueError(f"Invalid tithi sequence for {key}")
    seen.add(key)
    encoded = "".join(chr(96 + tithi) for tithi in tithis)
    lines.append(f"  ({year}, {month}, {str(bool(leap)).lower()}, '{encoded}'),")
lines.append("];")
args.dart_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
