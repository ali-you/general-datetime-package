"""Generate Chinese civil data from the MIT-licensed .NET 10.0.0 table.

python tool/generate_chinese_calendar.py [--offline] [--check]
Input hash is pinned. Independent .NET runtime fixtures are exported with
export_chinese_oracle.ps1; HKO is a validation reference, not shipped data.
"""
import argparse
import datetime as dt
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
URL = 'https://raw.githubusercontent.com/dotnet/runtime/v10.0.0/src/libraries/System.Private.CoreLib/src/System/Globalization/ChineseLunisolarCalendar.cs'
SHA256 = 'f6a6a3e586571e6afeaa347ad26d7b9ade0a2a160667b62539feac4c6cf7ada6'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    cache = ROOT / 'tool/.chinese-cache/ChineseLunisolarCalendar.cs'
    if not cache.exists():
        if args.offline:
            raise ValueError('Pinned source is not cached')
        cache.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(URL, timeout=45) as response:
            cache.write_bytes(response.read())
    raw = cache.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('Pinned .NET source hash mismatch')
    matches = re.findall(r'(\d{4})\s+\*/\s*\{\s*(\d+),\s*(\d+),\s*(\d+),\s*0b([01]+)', raw.decode())
    assert len(matches) == 200
    rows = []
    previous_end = None
    for year, leap, month, day, bits in matches[:-1]:
        year, leap, month, day = map(int, (year, leap, month, day))
        start = dt.date(year, month, day)
        if previous_end is not None:
            assert start == previous_end
        length_bits = bits[:13 if leap else 12]
        length = sum(29 + int(bit) for bit in length_bits)
        previous_end = start + dt.timedelta(days=length)
        mask = sum(int(bit) << i for i, bit in enumerate(length_bits))
        rows.append(f'  ({(start - dt.date(1970, 1, 1)).days}, {leap}, 0x{mask:04x}), // {year}')
    outputs = {
        ROOT / 'packages/general_datetime_core/lib/src/calendars/chinese/chinese_calendar_data.dart':
            '// Generated by tool/generate_chinese_calendar.py. Do not edit.\n'
            '// Derived from .NET 10.0.0 (MIT); see THIRD_PARTY_NOTICES.md.\n'
            '// (Gregorian epoch day of New Year, repeated lunar month or 0,\n'
            '// chronological month-length bits: 1 = 30 days, 0 = 29).\n'
            'const chineseCalendarData = <(int, int, int)>[\n' + '\n'.join(rows) + '\n];\n',
        ROOT / 'tool/chinese_sources.json': json.dumps({'url': URL, 'sha256': SHA256,
            'license': 'MIT', 'minimumYear': 1901, 'maximumYear': 2099}, indent=2) + '\n',
    }
    for path, text in outputs.items():
        if args.check:
            if path.read_text(encoding='utf-8') != text:
                raise ValueError(f'Generated output differs: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
    print(f'{"Verified" if args.check else "Generated"} {len(rows)} lunar years from pinned .NET source.')


if __name__ == '__main__':
    main()
